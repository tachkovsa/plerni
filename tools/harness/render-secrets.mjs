#!/usr/bin/env node
// render-secrets.mjs — writes pgbouncer/userlist.txt from the environment.
// The output is gitignored. PgBouncer accepts plaintext passwords when
// auth_type = scram-sha-256.
//
// The image reads the mount as uid/gid 70. The file is never world-readable,
// and this script never runs interactive sudo:
// 1. Write mode 0600, then set the group to 70 and chmod 0640. chown is tried
//    directly. On EPERM, the only retry is `sudo -n chgrp` (no password prompt).
// 2. If group 70 cannot be set that way, write the file mode 0600 inside
//    pgbouncer/private (directory 0700) and point userlist.txt at it. A
//    gitignored docker-compose.override.yml starts pgbouncer as the invoker,
//    who can read that directory. Other local accounts cannot.
// 3. If that fallback cannot be published, exit non-zero. Re-run as root, as
//    a member of group 70, or where `sudo -n chgrp` is allowed.
import { execFileSync } from 'node:child_process';
import {
  chmodSync,
  chownSync,
  mkdirSync,
  rmSync,
  statSync,
  symlinkSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const IMAGE_GID = 70;

const required = ['PLERNI_APP_PASSWORD', 'PLERNI_MIGRATE_PASSWORD', 'PLERNI_ADMIN_PASSWORD'];
const missing = required.filter((key) => !process.env[key]);
if (missing.length) {
  console.error(`render-secrets: missing env vars: ${missing.join(', ')}`);
  process.exit(1);
}
if (typeof process.getuid !== 'function' || typeof process.getgid !== 'function') {
  console.error('render-secrets: this host cannot report the invoker uid/gid.');
  process.exit(1);
}

const harnessDir = dirname(fileURLToPath(import.meta.url));
const pgbouncerDir = join(harnessDir, 'pgbouncer');
const target = join(pgbouncerDir, 'userlist.txt');
const privateDir = join(pgbouncerDir, 'private');
const overridePath = join(harnessDir, 'docker-compose.override.yml');
const lines = [
  `"plerni_app" "${process.env.PLERNI_APP_PASSWORD}"`,
  `"plerni_migrate" "${process.env.PLERNI_MIGRATE_PASSWORD}"`,
  `"plerni_admin_ro" "${process.env.PLERNI_ADMIN_PASSWORD}"`,
];
const body = lines.join('\n') + '\n';
const uid = process.getuid();
const gid = process.getgid();

function removePath(path) {
  try {
    unlinkSync(path);
  } catch (err) {
    if (err.code !== 'ENOENT') throw err;
  }
}

function clearFallback() {
  rmSync(privateDir, { recursive: true, force: true });
  rmSync(overridePath, { force: true });
}

function tryDirectGroup(path) {
  try {
    chownSync(path, uid, IMAGE_GID);
  } catch (err) {
    if (err.code !== 'EPERM' && err.code !== 'EACCES') throw err;
    return false;
  }
  return statSync(path).gid === IMAGE_GID;
}

function trySudoGroup(path) {
  try {
    execFileSync('sudo', ['-n', 'chgrp', String(IMAGE_GID), path], { stdio: 'ignore' });
  } catch {
    return false;
  }
  return statSync(path).gid === IMAGE_GID;
}

function writeGrouped() {
  removePath(target);
  writeFileSync(target, body, { mode: 0o600 });
  if (!tryDirectGroup(target) && !trySudoGroup(target)) return false;
  chmodSync(target, 0o640);
  clearFallback();
  return statSync(target).gid === IMAGE_GID;
}

function writePrivate() {
  mkdirSync(privateDir, { recursive: true, mode: 0o700 });
  chmodSync(privateDir, 0o700);
  const secret = join(privateDir, 'userlist.txt');
  writeFileSync(secret, body, { mode: 0o600 });
  chmodSync(secret, 0o600);
  removePath(target);
  symlinkSync(join('private', 'userlist.txt'), target);
  writeFileSync(
    overridePath,
    [
      '# Generated by render-secrets.mjs when group 70 cannot be set. Gitignored.',
      'services:',
      '  pgbouncer:',
      `    user: "${uid}:${gid}"`,
      '',
    ].join('\n'),
    { mode: 0o600 },
  );
  const dirMode = statSync(privateDir).mode & 0o777;
  const fileMode = statSync(secret).mode & 0o777;
  if (dirMode !== 0o700 || fileMode !== 0o600) {
    throw new Error(`private directory mode ${dirMode.toString(8)}, file mode ${fileMode.toString(8)}`);
  }
}

if (writeGrouped()) {
  console.log(`render-secrets: wrote ${target} (mode 640, group ${IMAGE_GID}, gitignored)`);
} else {
  try {
    writePrivate();
  } catch (err) {
    console.error('render-secrets: could not make the userlist readable by pgbouncer.');
    console.error(
      `Group ${IMAGE_GID} is not settable without an interactive password, and the mode-600 file in a 0700 directory could not be published (${err instanceof Error ? err.message : err}).`,
    );
    console.error(
      `Re-run as root, as a member of group ${IMAGE_GID}, or on a host where \`sudo -n chgrp\` is allowed. This script will not prompt for a password.`,
    );
    process.exit(1);
  }
  console.log(
    `render-secrets: wrote ${join(privateDir, 'userlist.txt')} (mode 600, directory 700). Group ${IMAGE_GID} was not available; pgbouncer runs as uid ${uid}.`,
  );
}
