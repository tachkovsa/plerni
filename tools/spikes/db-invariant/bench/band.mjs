// Band model for the Spike A typecheck benchmark (plan §3.1 A5).
// N counts every table in the band, including plugin_lrs_statement.
// Harness fixture tables live in the plerni database and are not part of N.

import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const BANDS = [50, 75, 200, 400];
export const ACCEPTANCE_BAND = 75;
export const CEILING_WALL_MS = 120_000;
// 4 GB RSS, read as 4 GiB. /usr/bin/time reports kibibytes.
export const CEILING_RSS_KIB = 4 * 1024 * 1024;
export const REPETITIONS = 3;

export const spikeRoot = join(dirname(fileURLToPath(import.meta.url)), '..');

export function assertBand(n) {
  if (!BANDS.includes(n)) {
    throw new Error(`band must be one of ${BANDS.join(', ')}`);
  }
}

export function allocation(n) {
  if (!Number.isInteger(n) || n <= 0) throw new Error('N must be a positive integer');
  const s = 3 * n;
  const m = Math.floor(1.5 * n);
  const l = 5 * n - s - m;
  if (s + m + l !== 5 * n) throw new Error(`allocation does not sum to 5N for N=${n}`);
  if (m < 20 || l < 10) throw new Error(`shape floors failed for N=${n} (M=${m}, L=${l})`);
  return { s, m, l, total: 5 * n };
}

export function benchDatabase(n) {
  assertBand(n);
  return `spike_bench_${n}`;
}

export function artifactDir(n) {
  assertBand(n);
  return join(spikeRoot, 'bench', '.artifacts', `band-${n}`);
}

function entityName(i) {
  return `ent_${String(i).padStart(4, '0')}`;
}

// Chains of four entities so a query can use three JOIN clauses.
export function bandModel(n) {
  assertBand(n);
  const entityCount = n - 1;
  const entities = [];
  for (let i = 1; i <= entityCount; i++) {
    const pos = (i - 1) % 4;
    const name = entityName(i);
    const parent = pos === 0 ? null : entities[entities.length - 1].name;
    entities.push({ name, kind: 'entity', parent, pos });
  }
  const chains = [];
  for (let i = 0; i + 3 < entities.length; i += 4) {
    chains.push(entities.slice(i, i + 4));
  }
  if (chains.length < 1) throw new Error(`band ${n} has no 4-table chain`);
  const statement = { name: 'plugin_lrs_statement', kind: 'statement', parent: null, pos: 0 };
  return {
    n,
    entities,
    statement,
    tables: [...entities, statement],
    chains,
    allocation: allocation(n),
  };
}

export function renderSchema(n) {
  const model = bandModel(n);
  const lines = [
    '-- Generated by tools/spikes/db-invariant/bench/gen-schema.mjs',
    `-- Band N=${n}. N counts every table in this database, including plugin_lrs_statement.`,
    '-- Harness fixture tables (plerni_tenant, fencing_authority) live in the plerni database and are excluded.',
    '-- Annex L payload class: JSON, 0.5-4 KiB typical, p99 <= 32 KiB. Append-only via trigger.',
    '',
  ];
  for (const table of model.entities) {
    lines.push(`CREATE TABLE ${table.name} (`);
    lines.push('  id uuid PRIMARY KEY,');
    lines.push('  tenant_id uuid NOT NULL,');
    if (table.parent) {
      lines.push(`  parent_id uuid REFERENCES ${table.parent} (id),`);
    } else {
      lines.push('  parent_id uuid,');
    }
    lines.push('  label text NOT NULL,');
    lines.push('  status text NOT NULL,');
    lines.push('  seq bigint NOT NULL,');
    lines.push('  amount numeric(12, 2) NOT NULL,');
    lines.push('  note text,');
    lines.push('  created_at timestamptz NOT NULL DEFAULT clock_timestamp()');
    lines.push(');');
    lines.push(`CREATE INDEX ${table.name}_keyset ON ${table.name} (tenant_id, seq, id);`);
    lines.push('');
  }
  const statement = model.statement.name;
  lines.push(`CREATE TABLE ${statement} (`);
  lines.push('  id uuid PRIMARY KEY,');
  lines.push('  tenant_id uuid NOT NULL,');
  lines.push('  seq bigint NOT NULL,');
  lines.push('  stored_at timestamptz NOT NULL DEFAULT clock_timestamp(),');
  lines.push('  payload jsonb NOT NULL,');
  lines.push(`  CONSTRAINT ${statement}_payload_p99 CHECK (octet_length(payload::text) <= 32768)`);
  lines.push(');');
  lines.push(`COMMENT ON COLUMN ${statement}.payload IS 'Annex L: JSON, 0.5-4 KiB typical, p99 <= 32 KiB';`);
  lines.push(`CREATE INDEX ${statement}_keyset ON ${statement} (tenant_id, stored_at, id);`);
  lines.push('');
  lines.push('CREATE FUNCTION plugin_lrs_statement_reject_mutation()');
  lines.push('RETURNS trigger');
  lines.push('LANGUAGE plpgsql');
  lines.push('AS $fn$');
  lines.push('BEGIN');
  lines.push("  RAISE EXCEPTION 'plugin_lrs_statement is append-only';");
  lines.push('END;');
  lines.push('$fn$;');
  lines.push('');
  lines.push('CREATE TRIGGER plugin_lrs_statement_append_only');
  lines.push(`  BEFORE UPDATE OR DELETE ON ${statement}`);
  lines.push('  FOR EACH ROW');
  lines.push('  EXECUTE FUNCTION plugin_lrs_statement_reject_mutation();');
  lines.push('');
  lines.push(`REVOKE UPDATE, DELETE ON ${statement} FROM PUBLIC;`);
  lines.push('');
  return lines.join('\n');
}
